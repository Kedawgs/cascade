import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { scanScript } from "../src/site.ts";

// pnpm site:approved ../web/out
//
// Writes src/site-approved.ts: every 0x-address and https host in the static export about to be deployed (its
// HTML and its _next/static JavaScript), which the site check compares the live site against (spec 6.6). Run
// it on the build you deploy, review the lists in git, then deploy the Worker with them. It also prints the
// largest file: on Workers Free a chunk near the byte cap (SITE_MAX_BYTES) can use up a run's CPU.

const TARGET = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "site-approved.ts");

/** The export's HTML files and its _next/static scripts, with their text and size. */
export function readOut(dir: string): { path: string; text: string; bytes: number }[] {
  const walk = (d: string): string[] => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
  return walk(dir)
    .map((f) => ({ f, rel: relative(dir, f).split(sep).join("/") }))
    .filter(({ rel }) => rel.endsWith(".html") || (rel.startsWith("_next/static/") && rel.endsWith(".js")))
    .map(({ f, rel }) => {
      const text = readFileSync(f, "utf8");
      return { path: `/${rel}`, text, bytes: Buffer.byteLength(text) };
    });
}

export function approvedLists(files: readonly { path: string; text: string; bytes: number }[]) {
  const addresses = new Set<string>();
  const hosts = new Set<string>();
  let largest = { path: "", bytes: 0 };
  for (const f of files) {
    const s = scanScript(f.text);
    for (const a of s.addresses) addresses.add(a);
    for (const h of s.hosts) hosts.add(h);
    if (f.bytes > largest.bytes) largest = { path: f.path, bytes: f.bytes };
  }
  return { addresses: [...addresses].sort(), hosts: [...hosts].sort(), largest };
}

export function renderApproved(lists: { addresses: string[]; hosts: string[] }, date: string): string {
  const list = (xs: string[]) => (xs.length ? `[\n${xs.map((x) => `  "${x}",`).join("\n")}\n]` : "[]");
  return [
    `// Generated by \`pnpm site:approved ../web/out\` (scripts/site-approved.ts), built ${date}: every 0x-address and https`,
    "// host in the static export deployed. The site check reports anything else (spec 6.6). Review changes in git.",
    "",
    `export const APPROVED_ADDRESSES: readonly string[] = ${list(lists.addresses)};`,
    "",
    `export const APPROVED_HOSTS: readonly string[] = ${list(lists.hosts)};`,
    "",
  ].join("\n");
}

export async function main(argv: string[], o: { target: string; print: (l: string) => void; today: () => string }): Promise<number> {
  const dir = argv.filter((a) => a !== "--")[0];
  if (!dir) {
    o.print("usage: pnpm site:approved <web/out directory>");
    return 2;
  }
  const files = readOut(dir);
  const lists = approvedLists(files);
  writeFileSync(o.target, renderApproved(lists, o.today()));
  o.print(`${files.length} files: ${lists.addresses.length} addresses, ${lists.hosts.length} hosts written to ${o.target}`);
  o.print(`largest file: ${lists.largest.path} (${lists.largest.bytes} bytes); on Workers Free keep it well under SITE_MAX_BYTES or set SITE_FILES_PER_RUN=1`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2), { target: TARGET, print: (l) => console.log(l), today: () => new Date().toISOString().slice(0, 10) }).then((c) => process.exit(c));
}
